(** Actual finite-prefix carry, with the normal return frame generated by
    inserting the one required by the machine's decrement branch. *)
From PAModel Require Import Model Arithmetic CodeExpressions TM230BinaryStep TM230BitArithmetic
 TM230Paths TM230ExactPaths TM230UnaryBlocks TM230ReverseBlocks TM230RegisterPrefix
 TM230CarryPlain TM230CarryPrefixes TM230IncrementAlignment.
From Stdlib Require Import Lists.List.
Import ListNotations.
Unset Implicit Arguments.
Theorem machine230_carry_physical_prefix M values left tail word s:
 machine230_blocks_list M values tail word ->machine230_right_view M 0 left word s ->
 exists out t,machine230_prefix_frame M values
  (addM M(succM M(zeroM M))(mulM M(code_numeral M 2)left))tail word
  (addM M(succM M(zeroM M))(mulM M(code_numeral M 2)out)) /\
 machine230_right_view M 0 out tail t /\machine230_reaches M s t.
Proof.
 revert left word s. induction values as[|v vs IH];intros left word s Hblocks Hs.
 -change(word=tail)in Hblocks. subst word. exists left,s. split;[split;reflexivity|].
  split;[exact Hs|apply machine230_reaches_refl].
 -destruct Hblocks as[middle[Htail Hhead]].
  destruct(machine230_carry_plain_block M v left middle word s Hhead Hs)
   as[p[k[mid[Hp[Hpk[Hmid Hpath]]]]]].
  set(nextleft:=addM M(mulM M p(addM M(mulM M(code_numeral M 4)left)(code_numeral M 2)))k).
  assert(Hstep:machine230_carry_prefix_step M v left nextleft).
  {exists p,k;split;[exact Hp|]. split;[exact Hpk|reflexivity]. }
  pose proof(machine230_carry_inserted_one M v left nextleft Hstep)as Hrev.
  destruct(IH nextleft middle mid Htail Hmid)as[out[t[Hframe[Ht Hrest]]]].
  exists out,t. split.
  +exists middle,(addM M(succM M(zeroM M))(mulM M(code_numeral M 2)nextleft)). auto.
  +split;[exact Ht|]. eapply machine230_reaches_trans;[|exact Hrest].
   eapply machine230_reaches_in_forget;exact Hpath.
Qed.
Print Assumptions machine230_carry_physical_prefix.

