Theorem source_conditional_fact_self M condition k:
 source_bounded M condition k ->source_conditional_fact M condition condition.
Proof.
 intros BC out HO. refine(source_zfr_prop_zero M(SPTImpl(SPTSlot 0)(SPTSlot 0))_
  (fun _=>condition)k out(fun _=>BC)_).
 - apply SPTII,SPTCtx. now left.
 - exact(source_prop_template_join M _ SFImpl(SPTSlot 0)(SPTSlot 0)condition condition out eq_refl eq_refl HO).
Qed.

Theorem source_binary_input_equality M phi u u' v before after condition q:
 source_bounded M phi(code_numeral M 2) ->coding_lt M u q ->coding_lt M u' q ->coding_lt M v q ->
 source_rec_binary M phi u v before ->source_rec_binary M phi u' v after ->
 sf_relation M SFEqual u u' condition ->source_conditional_equivalent M condition before after.
Proof.
 intros BP BU BU' BV HA HB HC.
 pose proof(source_rec_binary_bounded M phi u v before q BP BU BV HA)as BA.
 pose proof(source_rec_binary_bounded M phi u' v after q BP BU' BV HB)as BB.
 pose proof(proj2(source_bounded_accept_atom M SFEqual u u' condition q(or_intror eq_refl)HC)(conj BU BU'))as BC.
 destruct HA as(ab&ac&HRoleA&HSubA). destruct HB as(bb&bc&HRoleB&HSubB).
 apply(source_equality_congruence_internal M phi condition(code_numeral M 2)
  ab ac(code_numeral M 2)(code_numeral M 2)bb bc(code_numeral M 2)(code_numeral M 2)before after q
  BP BC BA BB HSubA HSubB).
 intros i x y equal HI HX HY HE.
 destruct(source_numeral_initial_segment M 2 i HI)as(n&HN&->).
 pose proof(substitution_lookup_functional M _ _ _ _ _ x(if Nat.eqb n 0 then u else v)
  HX(source_pc_reopening_lookup M v u ab ac(code_numeral M 2)n HRoleA HN))as EX.
 pose proof(substitution_lookup_functional M _ _ _ _ _ y(if Nat.eqb n 0 then u' else v)
  HY(source_pc_reopening_lookup M v u' bb bc(code_numeral M 2)n HRoleB HN))as EY.
 subst x y. destruct n as[|[|n]];try lia.
 - pose proof(sf_relation_functional M SFEqual u u' equal condition HE HC)as E. subst equal.
   exact(source_conditional_fact_self M condition q BC).
 - apply(source_conditional_fact_of_proof M condition equal q BC).
   + exact(proj2(source_bounded_accept_atom M SFEqual v v equal q(or_intror eq_refl)HE)(conj BV BV)).
   + exact(source_zfr_equal_reflexive M v equal HE).
Qed.

Theorem source_zfr_binary_input_equality M phi u u' v before after condition point law q:
 source_bounded M phi(code_numeral M 2) ->coding_lt M u q ->coding_lt M u' q ->coding_lt M v q ->
 source_rec_binary M phi u v before ->source_rec_binary M phi u' v after ->
 sf_relation M SFEqual u u' condition ->sf_relation M SFImpl before after point ->
 sf_relation M SFImpl condition point law ->source_zfr_provable M law.
Proof.
 intros BP BU BU' BV HA HB HC HP HL.
 exact(proj1(source_binary_input_equality M phi u u' v before after condition q BP BU BU' BV HA HB HC)point HP law HL).
Qed.
